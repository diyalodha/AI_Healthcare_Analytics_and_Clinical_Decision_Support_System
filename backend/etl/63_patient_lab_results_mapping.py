
import os
import sys
import mysql.connector
from mysql.connector import Error

# ============================================================
# STEP 63 - PATIENT LAB RESULTS MAPPING
# Resumable, batched, and safe to rerun
# ============================================================

DB_CONFIG = {
    "host": "localhost",
    "port": 3306,
    "user": "root",
    "database": "healthcare_ai_db",
    "charset": "utf8mb4",
    "connection_timeout": 30,
}

SOURCE_TABLE = "lab_results"
TARGET_TABLE = "patient_lab_results_map"
BATCH_SIZE = 5000

BASE_DIR = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "..")
)

CHECKPOINT_FILE = os.path.join(
    BASE_DIR,
    "backend",
    "etl",
    ".63_patient_lab_results_mapping_checkpoint.txt",
)


def get_connection():
    password = os.environ.get("MYSQL_PASSWORD")

    if not password:
        import getpass
        password = getpass.getpass("MySQL root password: ")

    config = DB_CONFIG.copy()
    config["password"] = password
    return mysql.connector.connect(**config)


def get_table_columns(cursor, table_name):
    cursor.execute(
        """
        SELECT COLUMN_NAME, IS_NULLABLE, COLUMN_DEFAULT, EXTRA
        FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = %s
          AND TABLE_NAME = %s
        ORDER BY ORDINAL_POSITION
        """,
        (DB_CONFIG["database"], table_name),
    )
    return cursor.fetchall()


def read_checkpoint():
    if not os.path.exists(CHECKPOINT_FILE):
        return ""

    with open(CHECKPOINT_FILE, "r", encoding="utf-8") as file:
        return file.read().strip()


def save_checkpoint(last_id):
    temporary_file = CHECKPOINT_FILE + ".tmp"

    with open(temporary_file, "w", encoding="utf-8") as file:
        file.write(str(last_id))

    os.replace(temporary_file, CHECKPOINT_FILE)


def main():
    connection = None
    cursor = None

    print("=" * 72)
    print("STEP 63 - PATIENT LAB RESULTS MAPPING")
    print("=" * 72)
    print(f"Source: {SOURCE_TABLE}")
    print(f"Target: {TARGET_TABLE}")
    print(f"Batch size: {BATCH_SIZE:,}")
    print("Existing lab_results data will NOT be modified.")
    print()

    try:
        connection = get_connection()
        cursor = connection.cursor()

        # ----------------------------------------------------
        # 1. Validate both tables
        # ----------------------------------------------------

        source_metadata = get_table_columns(cursor, SOURCE_TABLE)
        target_metadata = get_table_columns(cursor, TARGET_TABLE)

        if not source_metadata:
            raise RuntimeError(
                f"Source table '{SOURCE_TABLE}' was not found."
            )

        if not target_metadata:
            raise RuntimeError(
                f"Target table '{TARGET_TABLE}' was not found."
            )

        source_columns = {
            row[0] for row in source_metadata
        }

        target_column_names = [
            row[0] for row in target_metadata
        ]

        if "Lab_Result_ID" not in source_columns:
            raise RuntimeError(
                "Lab_Result_ID is missing from the source table."
            )

        if "Lab_Result_ID" not in target_column_names:
            raise RuntimeError(
                "Lab_Result_ID is missing from the mapping table."
            )

        # Use matching column names and preserve their values.
        # The mapping table's own primary key is generated by MySQL.
        common_columns = [
            name
            for name in target_column_names
            if name in source_columns
            and name != "Lab_Result_Map_ID"
        ]

        if not common_columns:
            raise RuntimeError(
                "No common source and target columns were found."
            )

        # Ensure no required target column is left without a value.
        common_set = set(common_columns)

        for name, nullable, default, extra in target_metadata:
            if name in common_set:
                continue

            extra_lower = (extra or "").lower()

            if (
                nullable == "NO"
                and default is None
                and "auto_increment" not in extra_lower
                and "generated" not in extra_lower
            ):
                raise RuntimeError(
                    f"Required target column '{name}' has no "
                    "matching source column or database default. "
                    "Mapping stopped before inserting data."
                )

        print(f"Matching columns: {len(common_columns)}")
        print("Matching columns:", ", ".join(common_columns))

        quoted_columns = ", ".join(
            f"`{name}`" for name in common_columns
        )

        placeholders = ", ".join(
            ["%s"] * len(common_columns)
        )

        select_sql = f"""
            SELECT {quoted_columns}
            FROM `{SOURCE_TABLE}`
            WHERE `Lab_Result_ID` > %s
            ORDER BY `Lab_Result_ID`
            LIMIT {BATCH_SIZE}
        """

        insert_sql = f"""
            INSERT INTO `{TARGET_TABLE}` ({quoted_columns})
            VALUES ({placeholders})
            ON DUPLICATE KEY UPDATE
                `Lab_Result_ID` = VALUES(`Lab_Result_ID`)
        """

        id_index = common_columns.index("Lab_Result_ID")
        last_id = read_checkpoint()

        print()
        if last_id:
            print("Resuming after the last saved Lab_Result_ID.")
        else:
            print("Starting mapping from the first lab result.")

        scanned = 0

        # ----------------------------------------------------
        # 2. Copy records in committed, resumable batches
        # ----------------------------------------------------

        while True:
            cursor.execute(select_sql, (last_id,))
            rows = cursor.fetchall()

            if not rows:
                break

            # The target table's Lab_Result_Map_ID is omitted.
            # MySQL generates it using the table's UUID default.
            cursor.executemany(insert_sql, rows)
            connection.commit()

            last_id = str(rows[-1][id_index])
            save_checkpoint(last_id)

            scanned += len(rows)

            print(
                f"Processed this run: {scanned:,} | "
                f"Last source ID: {last_id}"
            )

        # ----------------------------------------------------
        # 3. Verify final counts
        # ----------------------------------------------------

        cursor.execute(
            f"SELECT COUNT(*) FROM `{SOURCE_TABLE}`"
        )
        source_count = cursor.fetchone()[0]

        cursor.execute(
            f"SELECT COUNT(*) FROM `{TARGET_TABLE}`"
        )
        target_count = cursor.fetchone()[0]

        cursor.execute(
            f"""
            SELECT COUNT(*)
            FROM `{TARGET_TABLE}` AS m
            LEFT JOIN `{SOURCE_TABLE}` AS l
                ON l.Lab_Result_ID = m.Lab_Result_ID
            WHERE l.Lab_Result_ID IS NULL
            """
        )
        orphan_count = cursor.fetchone()[0]

        cursor.execute(
            f"""
            SELECT COUNT(*)
            FROM `{SOURCE_TABLE}` AS l
            LEFT JOIN `{TARGET_TABLE}` AS m
                ON m.Lab_Result_ID = l.Lab_Result_ID
            WHERE m.Lab_Result_ID IS NULL
            """
        )
        missing_count = cursor.fetchone()[0]

        print()
        print("=" * 72)
        print("MAPPING VALIDATION")
        print("=" * 72)
        print(f"Source lab results : {source_count:,}")
        print(f"Mapping rows       : {target_count:,}")
        print(f"Missing mappings   : {missing_count:,}")
        print(f"Orphan mappings    : {orphan_count:,}")

        if (
            source_count == target_count
            and missing_count == 0
            and orphan_count == 0
        ):
            print("\nSUCCESS: All lab results have matching mappings.")
        else:
            print(
                "\nWARNING: Counts do not fully match. "
                "Keep all backups and investigate before proceeding."
            )

    except (Error, RuntimeError) as error:
        if connection is not None:
            connection.rollback()

        print(f"\nERROR: {error}")
        sys.exit(1)

    except Exception as error:
        if connection is not None:
            connection.rollback()

        print(f"\nUNEXPECTED ERROR: {error}")
        raise

    finally:
        if cursor is not None:
            cursor.close()

        if connection is not None and connection.is_connected():
            connection.close()


if __name__ == "__main__":
    main()
