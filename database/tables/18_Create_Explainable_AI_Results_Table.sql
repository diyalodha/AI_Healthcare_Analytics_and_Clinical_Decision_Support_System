USE healthcare_ai_db;



DROP TABLE IF EXISTS Explainable_AI_Results;



CREATE TABLE Explainable_AI_Results (


    -- ======================================================
    -- Primary Key
    -- ======================================================

    XAI_Result_ID CHAR(36)
        NOT NULL PRIMARY KEY DEFAULT (UUID()),



    -- ======================================================
    -- Foreign Keys
    -- ======================================================

    Prediction_Session_ID CHAR(36)
        NOT NULL,


    Patient_ID CHAR(36)
        NOT NULL,



    -- ======================================================
    -- Explainability Information
    -- ======================================================

    Explanation_Method ENUM(

        'SHAP',

        'LIME',

        'Feature Importance',

        'Rule Based'

    )
    DEFAULT 'SHAP',



    Important_Features TEXT,


    Feature_Contribution TEXT,


    Positive_Factors TEXT,


    Negative_Factors TEXT,



    -- ======================================================
    -- Model Explanation
    -- ======================================================

    Model_Decision TEXT,


    Confidence_Explanation TEXT,


    Explanation_Score DECIMAL(5,2),



    -- ======================================================
    -- Human Validation
    -- ======================================================

    Reviewed_By_Doctor BOOLEAN
        DEFAULT FALSE,


    Doctor_Feedback TEXT,



    -- ======================================================
    -- Audit Information
    -- ======================================================

    Created_By VARCHAR(50),

    Updated_By VARCHAR(50),


    Created_At TIMESTAMP
        DEFAULT CURRENT_TIMESTAMP,


    Updated_At TIMESTAMP
        DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,



    -- ======================================================
    -- Foreign Key Constraints
    -- ======================================================

    CONSTRAINT FK_XAI_Session

    FOREIGN KEY (Prediction_Session_ID)

    REFERENCES Prediction_Sessions(Prediction_Session_ID)

    ON UPDATE CASCADE

    ON DELETE CASCADE,



    CONSTRAINT FK_XAI_Patient

    FOREIGN KEY (Patient_ID)

    REFERENCES Patients(Patient_ID)

    ON UPDATE CASCADE

    ON DELETE RESTRICT


);



-- ======================================================
-- Indexes
-- ======================================================


CREATE INDEX IDX_XAI_Patient
ON Explainable_AI_Results(Patient_ID);


CREATE INDEX IDX_XAI_Session
ON Explainable_AI_Results(Prediction_Session_ID);


CREATE INDEX IDX_XAI_Method
ON Explainable_AI_Results(Explanation_Method);



SHOW TABLES;

DESCRIBE Explainable_AI_Results;